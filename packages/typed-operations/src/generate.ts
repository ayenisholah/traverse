import { createHash } from "node:crypto";
import { codegen } from "@graphql-codegen/core";
import * as operations from "@graphql-codegen/typescript-operations";
import { Kind, parse, type DocumentNode, type OperationDefinitionNode } from "graphql";

export interface OperationDocument {
  /** Where the document came from, for error messages. */
  file: string;
  body: string;
}

/** The router looks a persisted operation up by the SHA-256 of its exact bytes (C-34). */
export const operationHash = (body: string): string =>
  createHash("sha256").update(body).digest("hex");

/** The file the router's file provider reads for one operation (C-34). */
export const persistedOperation = (body: string): { file: string; content: string } => ({
  file: `${operationHash(body)}.json`,
  content: `${JSON.stringify({ version: 1, body })}\n`,
});

const HEADER = `// Generated by npm run generate:router from router/operations. Don't edit it by hand.

/** An operation the public router holds, with the types of its variables and its data. */
export interface TypedOperation<Data, Variables> {
  name: string;
  /** Sent in place of the operation's text, because the public router runs persisted operations only. */
  sha256: string;
  /** Never set. They carry the types to whoever runs the operation. */
  data?: Data;
  variables?: Variables;
}
`;

const SUFFIX = { query: "Query", mutation: "Mutation", subscription: "Subscription" };

// One named operation per file, so a file's hash names exactly one thing the app can run.
const onlyOperation = (file: string, document: DocumentNode): OperationDefinitionNode => {
  const [first, ...rest] = document.definitions;
  if (first?.kind !== Kind.OPERATION_DEFINITION || rest.length > 0 || first.name === undefined) {
    throw new Error(`${file} must hold exactly one named operation`);
  }
  return first;
};

/**
 * Types for each operation, with the hash the router knows it by. It throws when a document
 * doesn't fit the schema, so a mismatch stops the build (FR-WB-12).
 */
export const generateTypedOperations = async (
  schemaSdl: string,
  documents: OperationDocument[],
): Promise<string> => {
  const parsed = documents.map(({ file, body }) => {
    const document = parse(body);
    const { name, operation } = onlyOperation(file, document);
    return { file, body, document, name: (name as { value: string }).value, operation };
  });
  const names = parsed.map(({ name }) => name);
  const repeated = names.find((name, index) => names.indexOf(name) !== index);
  if (repeated !== undefined) throw new Error(`Two operations are named ${repeated}`);

  const types = await codegen({
    filename: "operations.ts",
    schema: parse(schemaSdl),
    documents: parsed.map(({ file, document }) => ({ location: file, document })),
    plugins: [{ operations: {} }],
    pluginMap: { operations },
    config: {},
  });
  const constants = parsed.map(({ name, operation, body }) => {
    const type = `${name}${SUFFIX[operation]}`;
    return `export const ${name}Operation: TypedOperation<${type}, ${type}Variables> = {\n  name: ${JSON.stringify(name)},\n  sha256: "${operationHash(body)}",\n};\n`;
  });
  return [HEADER, types.trimEnd(), "", ...constants].join("\n");
};
